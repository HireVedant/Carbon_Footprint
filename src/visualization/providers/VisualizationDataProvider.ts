/**
 * Visualization Data Provider — Verified & Transparent
 *
 * Provides typed data for India Map layers and chart visualizations.
 * Every value has a traceable source. No fabricated numbers.
 *
 * DATA INTEGRITY RULES:
 *   - Government data: Verified against published datasets with source + year.
 *   - Community data: Marked "No community data" when Firestore lacks state-level tracking.
 *   - Estimated values: Clearly flagged with confidence < 70%.
 *   - All values have: source, year, confidence, estimated flag, government/community flag.
 *
 * SOURCES USED:
 *   - Census of India 2011 (population by state/UT)
 *   - MoSPI Population Projections 2011-2036 (latest official projections)
 *   - CEA CO₂ Baseline Database for India, v20.0, FY 2023-24
 *     (grid emission factor by regional/state utility)
 *   - Ember Climate — India State Electricity Explorer 2025
 *     (renewable share by state from CEA monthly data)
 *   - NITI Aayog — India's Greenhouse Gas Emissions 2007, 2012, 2018
 *     (state-level per-capita estimates, extrapolated to recent years)
 *   - Ministry of Power — Integrated Energy Policy reports
 *   - Bureau of Energy Efficiency (BEE) — State energy efficiency data
 *
 * IMPORTANT CAVEATS:
 *   - Population: Census 2011 is the last completed census. 2024 values
 *     use MoSPI projections (Series 2011 with revised TFR). These are
 *     official projections, not estimates from third parties.
 *   - Grid emission factor: CEA reports at regional grid level, not
 *     always at state level. Some states use their state utility's
 *     published data; others are approximated from the regional grid.
 *   - CO₂ per capita: NITI Aayog's GHG Platform reports state-level
 *     data for 2007, 2012, 2018. Recent values are extrapolated using
 *     national emission growth rates. These are estimates.
 *   - Renewable share: CEA publishes state-wise generation by source.
 *     Ember aggregates this. Values may differ slightly by reporting
 *     period (fiscal year vs calendar year).
 *   - Community data (participation, eco score): NOT AVAILABLE at
 *     state level. Firestore communityLeaderboard does not store
 *     state information. These layers show "No data" until
 *     state-level aggregation is implemented.
 */

import { MapLayer } from '../maps/IndiaMap';

// ── Type definitions ──────────────────────────────────────────────────────────
export interface StateDataRecord {
  stateName: string;
  population: number;            // Census 2011 actual (absolute count)
  populationProjected: number;   // MoSPI 2024 projected estimate
  populationSource: string;
  populationYear: string;

  // Grid emission factor
  gridFactor: number;            // gCO₂/kWh
  gridFactorSource: string;
  gridFactorYear: string;
  gridFactorConfidence: number;  // 0-1
  gridFactorEstimated: boolean;
  gridFactorNote: string;

  // Renewable energy share
  renewablePct: number;          // % of total generation
  renewableSource: string;
  renewableYear: string;
  renewableConfidence: number;
  renewableEstimated: boolean;

  // CO₂ per capita
  co2PerCapita: number;          // tCO₂e/yr
  co2Source: string;
  co2Year: string;
  co2Confidence: number;
  co2Estimated: boolean;
  co2Note: string;

  // Additional context
  transportPct: number;          // % of state GHG from transport (NITI Aayog)
  householdPct: number;          // % of state GHG from household energy

  // Community data (from Firestore)
  participation: number | null;  // null = no state-level data available
  ecoScore: number | null;       // null = no state-level data available
  communityConfidence: number;

  // Metadata
  lastUpdated: string;
  confidenceScore: number;       // overall confidence 0-1
  isGovernmentData: boolean;
  estimatedFields: string[];     // list of fields that are estimated
}

