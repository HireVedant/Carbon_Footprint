  static getOverallStats() {
    const states = Object.values(STATE_DATA);
    return {
      totalPopulation: states.reduce((s, v) => s + v.populationProjected, 0),
      avgEcoScore: null as number | null,  // Not available at state level
      avgCarbonKg: null as number | null,  // Not derived from community data
      avgRenewable: Math.round(states.reduce((s, v) => s + v.renewablePct, 0) / states.length),
      totalParticipation: null as number | null,  // Not available at state level
      avgGridFactor: Math.round(states.reduce((s, v) => s + v.gridFactor, 0) / states.length),
      avgCo2PerCapita: +(states.reduce((s, v) => s + v.co2PerCapita, 0) / states.length).toFixed(1),
    };
  }

